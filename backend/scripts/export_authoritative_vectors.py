"""Export authoritative product rows for a vector projection rebuild.

The vector index is deliberately not consulted by this command.  The only
runtime dependency is the read-only Firestore-compatible facade exposed by
``database._client``.  In a self-host deployment that facade is backed by
PostgreSQL (``FIRESTORE_PG_DSN``); in the managed deployment it is backed by
Firestore.  The same source shape therefore drives a Pinecone-to-Qdrant
rebuild without carrying a Pinecone export forward as authority.

Each namespace is emitted as strict JSONL with exactly ``id``, ``content`` and
``metadata`` fields.  ``manifest.json`` binds each file's bytes, count and
source collection.  No vector values are emitted: embeddings are generated by
the explicitly configured migration runtime after this source export is
verified.
"""

